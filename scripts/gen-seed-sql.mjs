// Writes supabase/migrations/002_functions_and_seed.sql from src/data/seed.js,
// so the database and the in-browser fallback always start from the same data.
import fs from 'node:fs';
import { PROFILES, POSTS, FOLLOWS, TRANSACTIONS } from '../src/data/seed.js';

const q = (v) => (v === null || v === undefined ? 'null' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const profiles = PROFILES.map((p) => `(${[p.id, p.kind, p.handle, p.name, p.category, p.tier, p.bio, p.avatar, p.cover, p.fans, p.posts_count, p.balance, p.sort].map(q).join(', ')})`).join(',\n    ');
const posts = POSTS.map((p) => `(${[p.creator_id, p.kind, p.title, p.caption, p.media, p.access, p.price, p.views, p.likes, p.comments].map(q).join(', ')}, now() - interval '${p.hoursAgo * 60} minutes')`).join(',\n    ');
const follows = FOLLOWS.map(([a, b, d]) => `(${q(a)}, ${q(b)}, now() - interval '${d} days')`).join(', ');
const tx = TRANSACTIONS.map(([u, t, s, a, usd, h]) => `(${[u, t, s, a, usd].map(q).join(', ')}, now() - interval '${h} hours')`).join(',\n    ');

const sql = `-- Generated by scripts/gen-seed-sql.mjs. Functions the app calls, plus the demo seed.

create or replace function seed_demo() returns void language plpgsql security definer set search_path = public as $$
begin
  delete from tool_runs where true; delete from transactions where true; delete from tips where true; delete from unlocks where true;
  delete from subscriptions where true; delete from follows where true; delete from posts where true; delete from profiles where true;
  insert into profiles (id, kind, handle, name, category, tier, bio, avatar, cover, fans, posts_count, balance, sort) values
    ${profiles};
  insert into posts (creator_id, kind, title, caption, media, access, price, views, likes, comments, created_at) values
    ${posts};
  insert into follows (fan_id, creator_id, created_at) values ${follows};
  insert into transactions (user_id, title, subtitle, amount, usd, created_at) values
    ${tx};
end $$;

create or replace function reset_demo() returns void language sql security definer set search_path = public as $$ select seed_demo() $$;

create or replace function follow_toggle(p_fan text, p_creator text) returns boolean language plpgsql security definer set search_path = public as $$
begin
  if exists (select 1 from follows where fan_id = p_fan and creator_id = p_creator) then
    delete from subscriptions where fan_id = p_fan and creator_id = p_creator;
    delete from follows where fan_id = p_fan and creator_id = p_creator;
    update profiles set fans = greatest(fans - 1, 0) where id = p_creator;
    return false;
  end if;
  insert into follows (fan_id, creator_id) values (p_fan, p_creator);
  update profiles set fans = fans + 1 where id = p_creator;
  return true;
end $$;

create or replace function spend(p_user text, p_amount int, p_title text, p_sub text) returns int language plpgsql security definer set search_path = public as $$
declare b int;
begin
  select balance into b from profiles where id = p_user for update;
  if b is null or b < p_amount then raise exception 'INSUFFICIENT_BALANCE'; end if;
  update profiles set balance = balance - p_amount where id = p_user returning balance into b;
  insert into transactions (user_id, title, subtitle, amount, usd) values (p_user, p_title, p_sub, -p_amount, p_amount / 100.0);
  return b;
end $$;

create or replace function top_up(p_user text, p_coins int, p_bonus int, p_usd numeric) returns int language plpgsql security definer set search_path = public as $$
declare b int;
begin
  update profiles set balance = balance + p_coins + p_bonus where id = p_user returning balance into b;
  insert into transactions (user_id, title, subtitle, amount, usd) values (p_user, 'Topped up',
    to_char(p_coins, 'FM999,999') || case when p_bonus > 0 then ' + ' || to_char(p_bonus, 'FM999,999') || ' free' else '' end, p_coins + p_bonus, p_usd);
  return b;
end $$;

create or replace function send_tip(p_fan text, p_creator text, p_amount int, p_note text) returns int language plpgsql security definer set search_path = public as $$
declare b int; h text;
begin
  if p_amount < 100 then raise exception 'MIN_TIP'; end if;
  select handle into h from profiles where id = p_creator;
  b := spend(p_fan, p_amount, 'Tip to @' || h, coalesce(nullif(p_note, ''), 'Tip'));
  insert into tips (fan_id, creator_id, amount, note) values (p_fan, p_creator, p_amount, nullif(p_note, ''));
  return b;
end $$;

create or replace function subscribe(p_fan text, p_creator text, p_plan text, p_price int) returns int language plpgsql security definer set search_path = public as $$
declare b int; h text;
begin
  select handle into h from profiles where id = p_creator;
  b := spend(p_fan, p_price, 'Subscribed to @' || h, p_plan);
  if not exists (select 1 from follows where fan_id = p_fan and creator_id = p_creator) then
    insert into follows (fan_id, creator_id) values (p_fan, p_creator);
    update profiles set fans = fans + 1 where id = p_creator;
  end if;
  insert into subscriptions (fan_id, creator_id, plan, price) values (p_fan, p_creator, p_plan, p_price)
    on conflict (fan_id, creator_id) do update set plan = excluded.plan, price = excluded.price, created_at = now();
  return b;
end $$;

create or replace function unlock_post(p_fan text, p_post bigint) returns int language plpgsql security definer set search_path = public as $$
declare b int; pr int; h text;
begin
  select p.price, pf.handle into pr, h from posts p join profiles pf on pf.id = p.creator_id where p.id = p_post;
  b := spend(p_fan, pr, 'Unlocked a post', '@' || h || ' · 1 photo');
  insert into unlocks (fan_id, post_id) values (p_fan, p_post) on conflict do nothing;
  return b;
end $$;

create or replace function publish_post(p_creator text, p_kind text, p_title text, p_caption text, p_media text, p_access text, p_price int, p_tools text[]) returns bigint language plpgsql security definer set search_path = public as $$
declare pid bigint; t text;
begin
  insert into posts (creator_id, kind, title, caption, media, access, price, boosted, promoted)
  values (p_creator, p_kind, p_title, p_caption, p_media, p_access, coalesce(p_price, 0), 'boost' = any(p_tools), 'promotion' = any(p_tools))
  returning id into pid;
  update profiles set posts_count = posts_count + 1 where id = p_creator;
  foreach t in array coalesce(p_tools, '{}') loop
    insert into tool_runs (creator_id, post_id, tool, hours, price) values (p_creator, pid, t,
      case t when 'boost' then 48 when 'promotion' then 72 when 'top_picks' then 1 else 0 end,
      case t when 'boost' then 19.99 when 'promotion' then 49.99 when 'top_picks' then 89.99 else 19.99 end);
  end loop;
  return pid;
end $$;

create or replace function buy_tool(p_creator text, p_post bigint, p_tool text, p_hours int, p_price numeric) returns bigint language plpgsql security definer set search_path = public as $$
declare rid bigint;
begin
  insert into tool_runs (creator_id, post_id, tool, hours, price) values (p_creator, p_post, p_tool, p_hours, p_price) returning id into rid;
  if p_post is not null and p_tool = 'boost' then update posts set boosted = true where id = p_post; end if;
  if p_post is not null and p_tool = 'promotion' then update posts set promoted = true where id = p_post; end if;
  return rid;
end $$;

revoke all on function seed_demo() from public, anon, authenticated;
revoke all on function spend(text, int, text, text) from public, anon, authenticated;
grant execute on function reset_demo(), follow_toggle(text, text), top_up(text, int, int, numeric), send_tip(text, text, int, text),
  subscribe(text, text, text, int), unlock_post(text, bigint), publish_post(text, text, text, text, text, text, int, text[]),
  buy_tool(text, bigint, text, int, numeric) to anon, authenticated;

select seed_demo();
`;
fs.writeFileSync('supabase/migrations/002_functions_and_seed.sql', sql);
console.log('wrote', sql.length, 'chars');
